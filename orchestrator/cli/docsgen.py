"""Generate reference docs from source definitions (docs/generated/*.md). `check` fails on drift."""

from __future__ import annotations

import json
import sys

from orchestrator import config as cfg
from orchestrator.schema import SCHEMAS

HEADER = "<!-- GENERATED by `acr docs generate` from source definitions. Do not edit by hand. -->\n\n"


def cli_md() -> str:
    from orchestrator.cli.main import build_parser

    p = build_parser()
    out = ["# CLI reference", "", "```text", p.format_help().replace("python -m orchestrator", "acr").rstrip(), "```", ""]
    for name, sp in p._subparsers._group_actions[0].choices.items():  # noqa: SLF001 - argparse has no public API
        out += [f"## `acr {name}`", "", "```text", sp.format_help().rstrip(), "```", ""]
    return "\n".join(out)


def skills_md() -> str:
    out = ["# Skill catalog", "", "| Skill | Version | Category | Model tier | Languages | Rules |", "|---|---|---|---|---|---|"]
    skills = cfg.load_skills()
    for s in skills.values():
        out.append(f"| `{s.id}` | {s.version} | {s.category} | {s.tier} | {', '.join(s.languages)} | {len(s.rules) + len(s.companions)} |")
    out += ["", "## Rules", "", "| Rule | Skill | Severity | Confidence | Kind | Title |", "|---|---|---|---|---|---|"]
    for s in skills.values():
        for r in s.rules:
            kind = "verified" if r["confidence"] == "high" else "hypothesis"
            out.append(f"| `{r['id']}` | `{s.id}` | {r['severity']} | {r['confidence']} | {kind} | {r['title']} |")
    companions = [(s, c) for s in skills.values() for c in s.companions]
    if companions:
        out += [
            "",
            "## Companion rules",
            "",
            "Diff-level: fire when files matching *When* change and nothing matching *Requires* changes in the same diff.",
            "",
            "| Rule | Skill | Severity | When | Line pattern | Requires | Title |",
            "|---|---|---|---|---|---|---|",
        ]
        for s, c in companions:
            pat = "yes" if c.get("pattern") else "-"
            out.append(
                f"| `{c['id']}` | `{s.id}` | {c['severity']} | {' '.join(f'`{g}`' for g in c['when'])} | {pat} | "
                f"{' '.join(f'`{g}`' for g in c['requires'])} | {c['title']} |"
            )
    return "\n".join(out) + "\n"


def models_md() -> str:
    out = [
        "# Model catalog",
        "",
        "Selection guide: [model selection](../operations/model-selection.md). "
        "Pick for a machine with `acr models recommend --ram-mb <MB> --policy <policy>`.",
        "",
        "| Model | Tier | Kind | Params | Arch | Ollama ref | License | Class | Context | Min RAM | Status | Digest |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for m in sorted(cfg.load_models().values(), key=lambda m: (m.tier != "small", m.params_b)):
        arch = m.raw.get("architecture", "")
        if m.raw.get("active_params_b"):
            arch += f" ({m.raw['active_params_b']}B active)"
        out.append(
            f"| `{m.id}` | {m.tier} | {m.kind} | {m.params_b}B | {arch} | `{m.ref}` | {m.license} | {m.license_class} | "
            f"{m.context_tokens} | {m.min_ram_mb} MB | {m.status} | {'pinned' if m.digest else 'unpinned'} |"
        )
    out += ["", "## Sources", ""]
    for m in sorted(cfg.load_models().values(), key=lambda m: m.id):
        links = ", ".join(f"[{i + 1}]({u})" for i, u in enumerate(m.raw.get("evidence", [])))
        out.append(f"- `{m.id}`: {links}" + (f" — {m.raw.get('notes', '')}" if m.raw.get("notes") else ""))
    return "\n".join(out) + "\n"


def profiles_md() -> str:
    out = [
        "# Profiles",
        "",
        "| Profile | Policy | Tiers | Small model | Large model | Max calls | Timeout (s) | Description |",
        "|---|---|---|---|---|---|---|---|",
    ]
    root = cfg.home()
    for d in sorted((root / "profiles").iterdir()):
        p = cfg.load_profile(d.name)
        r, b = p.get("routing", {}), p.get("budget", {})
        out.append(
            f"| `{p['id']}` | {p['policy']} | {', '.join(r.get('tiers', [])) or 'rules only'} | "
            f"{r.get('small_model') or '-'} | {r.get('large_model') or '-'} | {b.get('max_model_calls')} | "
            f"{b.get('review_timeout_s')} | {p['description']} |"
        )
    out += [
        "",
        "## Policies",
        "",
        "| Policy | Version | Block on | Model findings block | Fail on infra error | Description |",
        "|---|---|---|---|---|---|",
    ]
    for f in sorted((root / "policies" / "review").glob("*.toml")):
        d = cfg.load_toml(f)
        g = d.get("gate", {})
        out.append(
            f"| `{d['id']}` | {d['version']} | {g.get('block_on', 'major')} | "
            f"{g.get('model_findings_can_block', True)} (≥{g.get('model_min_confidence_to_block', 'low')}) | "
            f"{g.get('fail_on_infrastructure_error', False)} | {d.get('description', '')} |"
        )
    return "\n".join(out) + "\n"


def schemas_md() -> str:
    out = ["# Contracts and schemas", ""]
    for f in sorted(SCHEMAS.glob("*.schema.json")):
        s = json.loads(f.read_text())
        out += [f"## `{s.get('$id')}` — {s.get('title')}", "", f"Source: `orchestrator/schemas/{f.name}`", ""]
        props = s.get("properties", {})
        req = set(s.get("required", []))
        if props:
            out += ["| Field | Required | Type / values | Description |", "|---|---|---|---|"]
            for k, v in props.items():
                t = v.get("type") or (" \\| ".join(map(str, v["enum"])) if "enum" in v else "object")
                tstr = t if isinstance(t, str) else " \\| ".join(t)
                out.append(f"| `{k}` | {'yes' if k in req else ''} | {tstr} | {v.get('description', '')} |")
        out.append("")
    return "\n".join(out)


def env_md() -> str:
    from orchestrator.cli import envref

    out = ["# Configuration reference (environment)", "", "| Variable | Default | Purpose |", "|---|---|---|"]
    out += [f"| `{k}` | `{d}` | {p} |" for k, d, p in envref.VARIABLES]
    return "\n".join(out) + "\n"


GENERATORS = {
    "cli.md": cli_md,
    "skills.md": skills_md,
    "models.md": models_md,
    "profiles.md": profiles_md,
    "schemas.md": schemas_md,
    "configuration.md": env_md,
}


def main(check: bool = False) -> int:
    out_dir = cfg.home() / "docs" / "generated"
    out_dir.mkdir(parents=True, exist_ok=True)
    drift = []
    for name, gen in GENERATORS.items():
        text = HEADER + gen()
        path = out_dir / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                drift.append(name)
        else:
            path.write_text(text, encoding="utf-8")
    if drift:
        print(f"generated docs out of date: {', '.join(drift)} — run `make docs`", file=sys.stderr)
        return 1
    print("docs: up to date" if check else f"docs: wrote {len(GENERATORS)} files to docs/generated")
    return 0
